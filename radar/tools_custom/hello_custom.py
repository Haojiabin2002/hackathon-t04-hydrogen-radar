"""示例自定义工具 · 仿写模板

这个目录里的每个 .py 文件 = 一个可以给 agent 用的工具。照下面的契约写就行。

────────────────────────── 文件契约（两样，缺一不可）──────────────────────────
1) 模块级 TOOL 字典：
       TOOL = {
           "name": "小写字母开头的工具名",   # 不得为空、不得与内置工具重名
           "desc": "一句话说清这个工具干什么",  # 模型靠它决定要不要调
           "args": {"参数名": "参数说明"},      # 没有参数就写 {}
       }
2) 模块级 run(args) 函数：
       - 入参 args 是一个 dict（模型给的参数，已经过 JSON 解析）
       - 返回值必须是**可 JSON 序列化的 dict**
       - 参数不对/查不到，抛 ValueError("说人话的原因")，它会被当成工具错误喂回模型

────────────────────────── 安全说明（硬编码，文件改不了）──────────────────────────
· 自定义工具一律 **confirm=True**：agent 只能提议，必须人确认才执行。
  就算你在文件里写 confirm=False 也一概忽略——不能让上传的代码自己决定自己免检。
· 新装载的自定义工具 **默认停用**，要在看板「能力配置 → 工具」页手动启用。
· 装载失败（语法错、缺 TOOL、缺 run、重名…）只会跳过这一个文件并在界面上报错，
  不会拖垮服务；修好文件再点一次「重新装载」即可。
· 这段代码在本机服务进程里执行，权限和 radar 服务一样大。**只有人**能上传/编辑，
  模型没有任何能写这个目录的工具——别把这条边界打开。
· 写工具时守住项目死规矩：不许编造数据，不许绕人机验证，LLM 不可用就报错不降级。
"""

TOOL = {
    "name": "hello_custom",
    "desc": "示例工具：返回一句问候，外加当前注册表里的工具总数与已启用数。"
            "用来验证自定义工具装载链路是通的，没有业务用途。",
    "args": {"who": "可选，跟谁打招呼，默认「销售」"},
}


def run(args):
    # 只读自己项目的注册表，不碰文件系统、不发网络请求——自定义工具也该守这条。
    import tools

    who = str(args.get("who") or "销售").strip()[:40]
    if not who:
        raise ValueError("who 传了但是空的，要么别传要么给个名字")

    names = list(tools.REGISTRY)
    enabled = [n for n in names if tools.is_enabled(n)]
    return {
        "greeting": f"你好，{who}。这条回复来自自定义工具 hello_custom。",
        "tool_total": len(names),
        "tool_enabled": len(enabled),
        "custom_total": sum(1 for n, s in tools.REGISTRY.items() if s.get("custom")),
        "note": "示例工具，没有业务含义。仿写它来写你自己的工具。",
    }
